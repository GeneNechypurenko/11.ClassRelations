/*
==========================================================================================================================================
                                                            Вкладений клас
==========================================================================================================================================

  Іноді необхідно згрупувати взаємопов'язані класи під одним ім'ям, якщо вони тісно пов'язані один з одним. В такому випадку можна
  оголосити клас всередині іншого. Такий клас називають вкладеним (nested class).

  В такому зв'язку: клас у якому оголошено називають зовнішнім (outer), клас який оголошено - вкладеним (inner).

                                                        Правила вкладених класів
  1. Вкладений клас — повноцінний клас: свої поля, методи, конструктори, свої public і private.
  2. Вкладений клас — член зовнішнього класу, тому на нього діють специфікатори доступу. Ззовні до нього звертаються через
     оператор :: (Зовнішній::Вкладений), так само записують і тіло методу за межами класу (Зовнішній::Вкладений::метод).
  3. Вкладений клас має доступ до private-членів зовнішнього класу, але лише через об'єкт зовнішнього класу:
     покажчика this на зовнішній об'єкт у нього немає. За правилом він член зовнішнього класу.
  4. Зовнішній клас НЕ має доступу до private-членів вкладеного класу — лише до public, як і всі інші. За правилом він не член
     вкладеного класу.
  5. Оголошення вкладеного класу — це лише оголошення ТИПУ, а не поле. Об'єкт Game не містить Settings,
     поки в Game не оголошено поле цього типу.

                                                            Цілі та завдання
  - Логічно згрупувати типи: тип, який має сенс лише разом з одним класом, оголошується в цьому класі.
    Game::Settings — налаштування саме гри, назва сама це пояснює.
  - Уникнути конфлікту імен: Game::Settings і Player::Settings — два різні класи, які не заважають один одному.
  - Сховати деталі реалізації: private-вкладений тип користувачу класу не потрібен.
*/

class Game
{
public:
    // Public-вкладений клас: налаштування гри ззовні його створюють як Game::Settings
    class Settings
    {
    private:
        int volume;                       // гучність 0..100
        int difficulty;                   // складність 1..3

    public:
        Settings() : volume(50), difficulty(2)    // налаштування за замовчуванням
        {}

        bool setVolume(int volume);       // тіло — за межами класу (нижче)

        bool setDifficulty(int difficulty)
        {
            if (difficulty < 1 || difficulty > 3)
            {
                return false;
            }
            this->difficulty = difficulty;
            return true;
        }

        void print() const
        {
            cout << "гучність " << volume << ", складність " << difficulty;
        }

        //void showTitle(const Game& g) const
        //{
        //    cout << g.title;            // ОК: вкладений клас бачить private-поля зовнішнього
        //}
    };

private:
    string title;
    Settings settings;                    // поле вкладеного типу: після цього оголошення Game містить Settings

public:
    Game(const string& title, const Settings& settings) : title(title), settings(settings) {}

    Settings getSettings() const
    {
        return settings;
    }

    void changeSettings(const Settings& settings)
    {
        this->settings = settings;
    }

    void start() const
    {
        // cout << settings.volume;       // ПОМИЛКА: volume — private-член Settings
        cout << "Запуск гри «" << title << "»: ";
        settings.print();
        cout << endl;
    }
};

// Метод вкладеного класу за межами класу: Зовнішній::Вкладений::метод
bool Game::Settings::setVolume(int volume)
{
    if (volume < 0 || volume > 100)
    {
        return false;
    }
    this->volume = volume;
    return true;
}

int main()
{
    SetConsoleOutputCP(65001);
    SetConsoleCP(65001);

    cout << "1. Налаштування створюємо ззовні через Game::Settings" << endl;
    Game::Settings settings;              // Settings settings; — помилка: без Game:: ім'я не видно
    settings.print();
    cout << endl;

    if (!settings.setVolume(150))         // перевірка всередині вкладеного класу
    {
        cout << "Гучність 150 — недопустиме значення" << endl;
    }
    settings.setVolume(80);
    settings.setDifficulty(3);

    cout << endl << "2. Передаємо налаштування в гру" << endl;
    Game game("Підземелля", settings);
    game.start();

    cout << endl << "3. Гравець змінює налаштування в меню" << endl;
    Game::Settings current = game.getSettings();     // беремо поточні
    current.setDifficulty(1);                        // змінюємо одне значення
    game.changeSettings(current);                    // повертаємо в гру
    game.start();

    return 0;
}

