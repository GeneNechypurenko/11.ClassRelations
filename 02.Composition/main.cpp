using namespace std;

/*
==========================================================================================================================================
                                                              Композиція
==========================================================================================================================================

  Між класами бувають два основні типи відношень:
    - «є» (is-a): студент Є людиною — це успадкування (наступний урок);
    - «має» (has-a): студент МАЄ дату народження, група МАЄ студентів — це композиція або агрегація.

                                                          Поняття композиції
  КОМПОЗИЦІЯ — відношення «ціле — частина», у якому частина належить цілому і не існує без нього. Ціле само створює і само знищує частину.
  Час життя частини = час життя цілого. Одна частина належить лише одному цілому.
*/

class Date
{
private:
    int day;
    int month;
    int year;

public:
    // Конструктора за замовчуванням немає: дату без значень створити не можна
    Date(int day, int month, int year) : day(day), month(month), year(year)
    {}

    int getYear() const
    {
        return year;
    }

    void print() const
    {
        // Ведучий нуль для днів і місяців: 05.03.2004
        cout << (day < 10 ? "0" : "") << day << "."
            << (month < 10 ? "0" : "") << month << "." << year;
    }
};

// КОМПОЗИЦІЯ: Student містить Date як поле
class Student
{
private:
    string name;                          // string — теж композиція: рядок належить студенту
    Date birthDate;                       // поле-об'єкт: створюється і знищується разом зі Student

public:
    // birthDate можна створити ТІЛЬКИ тут, бо в Date немає конструктора за замовчуванням
    Student(const string& name, int day, int month, int year)
        : name(name), birthDate(day, month, year)   {}

    explicit Student(const string& name, const Date& birthDate)
        : name(name), birthDate(birthDate)  {}

    int getAge(int currentYear) const
    {
        return currentYear - birthDate.getYear();   // користуємося методом частини
    }

    void print() const
    {
        cout << name << ", дата народження: ";
        birthDate.print();                          // частина вміє виводити себе сама
        cout << endl;
    }
};

int main()
{
    SetConsoleOutputCP(65001);
    SetConsoleCP(65001);

    // Student olena("Олена Коваль", 5, 3, 2004);
    Student olena("Олена Коваль", Date(5, 3, 2004));    // разом зі студенткою створюється і її дата народження
    olena.print();
    cout << "Вік у 2026 році: " << olena.getAge(2026) << endl;

    // Копія студента містить власну копію дати: частини не спільні
    Student copy = olena;
    copy.print();

    return 0;
}   // olena і copy знищуються, а з ними — і їхні дати народження

